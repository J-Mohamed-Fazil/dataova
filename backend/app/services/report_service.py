    @classmethod
    def _build_vector_horizontal_bar_chart(
        cls,
        title: str,
        subtitle: str,
        data: List[Dict[str, Any]],
        width: float = 522.0,
        height: float = 125.0
    ) -> Drawing:
        """
        Renders a publication-grade vector horizontal bar chart with proportional
        tracks, percentage contribution shares, and crisp typography.
        """
        d = Drawing(width, height)
        # Background card
        d.add(Rect(0, 0, width, height, rx=4, ry=4, fillColor=colors.HexColor('#F8FAFC'), strokeColor=colors.HexColor('#E2E8F0'), strokeWidth=0.75))
        # Top header banner
        d.add(Rect(0, height - 22, width, 22, rx=4, ry=4, fillColor=colors.HexColor('#0F172A'), strokeColor=None))
        d.add(String(10, height - 15, title.upper(), fontName='Helvetica-Bold', fontSize=7.5, fillColor=colors.white))
        if subtitle:
            d.add(String(width - 10, height - 15, subtitle.upper()[:40], fontName='Helvetica-Bold', fontSize=6.5, fillColor=colors.HexColor('#38BDF8'), textAnchor='end'))

        clean_data = [item for item in data if isinstance(item.get("value"), (int, float)) and not math.isnan(item["value"])]
        if not clean_data:
            d.add(String(width / 2, height / 2 - 5, "No distribution data available", fontName='Helvetica-Oblique', fontSize=8, fillColor=colors.HexColor('#94A3B8'), textAnchor='middle'))
            return d

        display_items = clean_data[:5]
        total_sum = sum(item.get("value", 0) for item in display_items) or 1.0
        max_val = max(item.get("value", 0) for item in display_items) or 1.0
        palette = [
            colors.HexColor('#6366F1'),  # Indigo
            colors.HexColor('#06B6D4'),  # Cyan
            colors.HexColor('#10B981'),  # Emerald
            colors.HexColor('#F59E0B'),  # Amber
            colors.HexColor('#EC4899')   # Pink
        ]

        bar_track_x = 135.0
        bar_track_w = width - bar_track_x - 120.0
        n_items = len(display_items)
        row_height = (height - 30.0) / max(n_items, 1)

        for idx, item in enumerate(display_items):
            y = height - 26.0 - (idx + 1) * row_height + 4.0
            val = float(item.get("value", 0))
            pct = round((val / total_sum) * 100, 1)
            bar_w = max(4.0, (val / max_val) * bar_track_w)
            bar_color = palette[idx % len(palette)]

            lbl = str(item.get("label", ""))
            if len(lbl) > 18:
                lbl = lbl[:16] + ".."
            d.add(String(10, y + 2, lbl, fontName='Helvetica-Bold', fontSize=7, fillColor=colors.HexColor('#1E293B')))

            # Background Track
            d.add(Rect(bar_track_x, y, bar_track_w, 9.0, rx=2.5, ry=2.5, fillColor=colors.HexColor('#E2E8F0'), strokeColor=None))
            # Colored Value Bar
            d.add(Rect(bar_track_x, y, bar_w, 9.0, rx=2.5, ry=2.5, fillColor=bar_color, strokeColor=None))
            # Formatted Value & Share
            val_formatted = cls.format_cell_value(val)
            d.add(String(bar_track_x + bar_track_w + 8.0, y + 2, f"{val_formatted} ({pct}%)", fontName='Helvetica-Bold', fontSize=6.5, fillColor=colors.HexColor('#0F172A')))

        return d

