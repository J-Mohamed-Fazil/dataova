    # -------------------------------------------------------------
    # PDF Export Engine with Precision Alignment & Dynamic Widths
    # -------------------------------------------------------------
    @staticmethod
    def _clean_markdown_for_pdf(text: str) -> str:
        """Converts Markdown bold, italics, bullets, and special chars to valid ReportLab XML."""
        if not text:
            return ""
        # Escape ampersands not part of XML entity
        cleaned = re.sub(r'&(?!(?:amp|lt|gt|quot|apos);)', '&amp;', text)
        # Escape angle brackets
        cleaned = cleaned.replace("<", "&lt;").replace(">", "&gt;")
        # Bold: **text** -> <b>text</b>
        cleaned = re.sub(r'\*\*(.+?)\*\*', r'<b>\1</b>', cleaned)
        # Italic: only match *text* where * is not internal to identifiers
        cleaned = re.sub(r'(^|\s)\*([^\*]+?)\*(\s|$)', r'\1<i>\2</i>\3', cleaned)
        return cleaned

    @staticmethod
    def _safe_paragraph(text: str, style: ParagraphStyle) -> Paragraph:
        """Safely creates a ReportLab Paragraph, falling back to plain text if malformed markup."""
        try:
            return Paragraph(text, style)
        except Exception:
            plain_text = re.sub(r'<[^>]+>', '', text)
            return Paragraph(plain_text, style)

    @staticmethod
    def _calculate_col_widths(headers: List[str], rows: List[List[Any]], total_width: float = 522.0) -> List[float]:
        """Dynamically computes proportional column widths fitting total printable width exactly."""
        num_cols = len(headers)
        if num_cols == 0:
            return []
        if num_cols == 1:
            return [total_width]

        # Measure length heuristic
        weights = []
        for i in range(num_cols):
            header_len = len(str(headers[i]))
            max_cell_len = max([len(str(r[i])) for r in rows[:10]] + [header_len]) if rows else header_len
            # Apply log/sqrt smoothing to avoid ultra-wide single columns
            weight = math.sqrt(max(max_cell_len, 4))
            weights.append(weight)

        total_weight = sum(weights)
        col_widths = [(w / total_weight) * total_width for w in weights]
        
        # Enforce reasonable minimum width
        min_width = max(38.0, total_width / (num_cols * 2.5))
        for i in range(num_cols):
            if col_widths[i] < min_width:
                col_widths[i] = min_width

        # Renormalize to exact total_width
        current_sum = sum(col_widths)
        col_widths = [(w / current_sum) * total_width for w in col_widths]
        return col_widths

