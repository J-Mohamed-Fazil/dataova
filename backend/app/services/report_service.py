class NumberedCanvas(canvas.Canvas):
    """
    Two-pass canvas that automatically adds running headers, running footers,
    and accurate dynamic page counts ('Page X of Y').
    """
    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._saved_page_states = []

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_header_footer(num_pages)
            super().showPage()
        super().save()

    def draw_header_footer(self, page_count: int):
        self.saveState()
        self.setFont("Helvetica-Bold", 8)
        self.setFillColor(colors.HexColor("#64748B"))

        # Running Top Header (pages > 1)
        if self._pageNumber > 1:
            self.drawString(45, 755, "DATOVA AI • EXECUTIVE BUSINESS REPORT")
            self.setFont("Helvetica", 8)
            self.drawRightString(567, 755, "STRICTLY CONFIDENTIAL")
            self.setStrokeColor(colors.HexColor("#CBD5E1"))
            self.setLineWidth(0.75)
            self.line(45, 747, 567, 747)

        # Running Footer (all pages)
        self.setStrokeColor(colors.HexColor("#E2E8F0"))
        self.setLineWidth(0.5)
        self.line(45, 45, 567, 45)
        self.setFont("Helvetica", 7.5)
        self.drawString(45, 32, "Generated by Datova Autonomous Intelligence Engine • Dynamic Multi-Sheet Analytics")
        page_text = f"Page {self._pageNumber} of {page_count}"
        self.drawRightString(567, 32, page_text)
        self.restoreState()


class ReportService:

    @staticmethod
    def format_cell_value(val: Any) -> str:
        """Helper to format numbers, currencies, dates, and strings cleanly."""
        if val is None or (isinstance(val, float) and math.isnan(val)):
            return "—"
        if isinstance(val, (int, np.integer)):
            return f"{val:,}"
        if isinstance(val, (float, np.floating)):
            if abs(val) >= 1_000_000:
                return f"{val:,.2f}"
            if abs(val) >= 1_000:
                return f"{val:,.1f}"
            if abs(val) < 0.01 and val != 0:
                return f"{val:.4f}"
            return f"{val:,.2f}"
        if isinstance(val, pd.Timestamp):
            return val.strftime("%Y-%m-%d")
        val_str = str(val).strip()
        if len(val_str) > 36:
            return val_str[:33] + "..."
        return val_str

    @staticmethod
    def _extract_architecture_table(dataframes: Dict[str, pd.DataFrame]) -> Dict[str, Any]:
        """Builds a structured metadata table of all uploaded files and sheets."""
        headers = ["Table / Sheet Name", "Total Records", "Column Count", "Key Measures", "Key Dimensions", "Data Density"]
        rows = []
        for name, df in dataframes.items():
            num_cols = df.select_dtypes(include=[np.number]).columns.tolist()
            clean_nums = [c for c in num_cols if not c.lower().endswith("id") and not c.lower().endswith("code")]
            cat_cols = df.select_dtypes(include=["object", "category", "string"]).columns.tolist()
            clean_cats = [c for c in cat_cols if not c.lower().endswith("id")]
            
            non_null_pct = round((df.notnull().sum().sum() / max(df.size, 1)) * 100, 1)
            
            meas_sample = ", ".join(clean_nums[:2]) if clean_nums else "None"
            dim_sample = ", ".join(clean_cats[:2]) if clean_cats else "None"

            rows.append([
                name,
                f"{len(df):,}",
                f"{len(df.columns)}",
                meas_sample,
                dim_sample,
                f"{non_null_pct}%"
            ])

        return {
            "title": "Uploaded Dataset Architecture & Ingestion Profile",
            "subtitle": f"System inventory of {len(dataframes)} processed tabular source(s)",
            "headers": headers,
            "rows": rows,
            "alignments": ["left", "right", "right", "left", "left", "right"],
            "data": [headers, *rows]
        }

    @staticmethod
    def _extract_curated_sample_table(dataframes: Dict[str, pd.DataFrame]) -> Optional[Dict[str, Any]]:
        """Extracts high-signal representative records directly from the primary uploaded file."""
        if not dataframes:
            return None
        primary_name = list(dataframes.keys())[0]
        df = dataframes[primary_name]
        if df.empty:
            return None

        # Prioritize informative columns
        cols = list(df.columns)
        num_cols = df.select_dtypes(include=[np.number]).columns.tolist()
        cat_cols = df.select_dtypes(include=["object", "category", "string"]).columns.tolist()
        date_cols = [c for c in df.columns if "date" in c.lower() or "time" in c.lower() or "year" in c.lower()]

        selected_cols = []
        # Primary label / ID
        name_cols = [c for c in cols if any(k in c.lower() for k in ["name", "title", "sku", "product", "employee", "customer", "account", "id"])]
        if name_cols:
            selected_cols.append(name_cols[0])
        # Date column
        if date_cols and date_cols[0] not in selected_cols:
            selected_cols.append(date_cols[0])
        # Up to 2 categorical columns
        for c in cat_cols:
            if c not in selected_cols and len(selected_cols) < 4:
                selected_cols.append(c)
        # Up to 3 numeric columns
        clean_nums = [c for c in num_cols if not c.lower().endswith("id")]
        for c in clean_nums:
            if c not in selected_cols and len(selected_cols) < 7:
                selected_cols.append(c)

        # Fallback if too few
        for c in cols:
            if c not in selected_cols and len(selected_cols) < 6:
                selected_cols.append(c)

        # Select representative rows
        sample_df = df[selected_cols].copy()
        # If numeric metric exists, sort by highest value to show most significant items
        if clean_nums:
            sort_metric = clean_nums[0]
            sample_df = sample_df.sort_values(by=sort_metric, ascending=False).head(6)
        else:
            sample_df = sample_df.head(6)

        headers = list(sample_df.columns)
        rows = []
        alignments = []

        for col in headers:
            if col in num_cols:
                alignments.append("right")
            elif col in date_cols:
                alignments.append("center")
            else:
                alignments.append("left")

        for _, row in sample_df.iterrows():
            formatted_row = [ReportService.format_cell_value(row[c]) for c in headers]
            rows.append(formatted_row)

        return {
            "title": f"Representative Dataset Excerpt: '{primary_name}'",
            "subtitle": f"Top significant observations extracted directly from uploaded records",
            "headers": headers,
            "rows": rows,
            "alignments": alignments,
            "data": [headers, *rows]
        }

    @staticmethod
    def _extract_segment_breakdown_table(dataframes: Dict[str, pd.DataFrame]) -> Optional[Dict[str, Any]]:
        """Calculates dynamic category breakdown and contribution share from the uploaded data."""
        if not dataframes:
            return None
        primary_name = list(dataframes.keys())[0]
        df = dataframes[primary_name]
        
        cat_cols = [c for c in df.select_dtypes(include=["object", "category", "string"]).columns if 2 <= df[c].nunique() <= 35 and not c.lower().endswith("id")]
        num_cols = [c for c in df.select_dtypes(include=[np.number]).columns if not c.lower().endswith("id") and not c.lower().endswith("code")]

        if not cat_cols or not num_cols:
            return None

        cat_col = cat_cols[0]
        num_col = num_cols[0]

        grouped = df.groupby(cat_col)[num_col].agg(["sum", "mean", "count"]).reset_index()
        grouped = grouped.sort_values(by="sum", ascending=False).head(6)
        
        total_sum = df[num_col].sum()
        
        headers = [cat_col.replace("_", " ").title(), "Record Count", f"Total {num_col.replace('_', ' ').title()}", f"Average {num_col.replace('_', ' ').title()}", "Contribution Share"]
        rows = []
        for _, r in grouped.iterrows():
            share_pct = round((r["sum"] / total_sum) * 100, 1) if total_sum > 0 else 0.0
            rows.append([
                str(r[cat_col]),
                f"{int(r['count']):,}",
                ReportService.format_cell_value(r["sum"]),
                ReportService.format_cell_value(r["mean"]),
                f"{share_pct}%"
            ])

        return {
            "title": f"Distribution Breakdown by {cat_col.replace('_', ' ').title()} & {num_col.replace('_', ' ').title()}",
            "subtitle": f"Aggregated performance across prominent segments in '{primary_name}'",
            "headers": headers,
            "rows": rows,
            "alignments": ["left", "right", "right", "right", "right"],
            "data": [headers, *rows]
        }

    @staticmethod
    def _extract_statistical_profile_table(dataframes: Dict[str, pd.DataFrame]) -> Optional[Dict[str, Any]]:
        """Computes statistical moments (mean, median, min, max, std dev) for key numeric columns."""
        if not dataframes:
            return None
        primary_name = list(dataframes.keys())[0]
        df = dataframes[primary_name]
        
        num_cols = [c for c in df.select_dtypes(include=[np.number]).columns if not c.lower().endswith("id") and not c.lower().endswith("code")]
        if not num_cols:
            return None

        headers = ["Numerical Measure", "Mean", "Median", "Min", "Max", "Std Dev", "Valid Coverage"]
        rows = []
        for col in num_cols[:6]:
            series = df[col].dropna()
            if series.empty:
                continue
            mean_val = series.mean()
            median_val = series.median()
            min_val = series.min()
            max_val = series.max()
            std_val = series.std() if len(series) > 1 else 0.0
            coverage_pct = round((len(series) / max(len(df), 1)) * 100, 1)

            rows.append([
                col.replace("_", " ").title(),
                ReportService.format_cell_value(mean_val),
                ReportService.format_cell_value(median_val),
                ReportService.format_cell_value(min_val),
                ReportService.format_cell_value(max_val),
                ReportService.format_cell_value(std_val),
                f"{coverage_pct}%"
            ])

        if not rows:
            return None

        return {
            "title": "Statistical Parameter & Dispersion Matrix",
            "subtitle": f"Parametric distributions calculated across numerical features in '{primary_name}'",
            "headers": headers,
            "rows": rows,
            "alignments": ["left", "right", "right", "right", "right", "right", "right"],
            "data": [headers, *rows]
        }

    @staticmethod
    def _extract_temporal_table(dataframes: Dict[str, pd.DataFrame]) -> Optional[Dict[str, Any]]:
        """Extracts temporal cadence if date columns are present."""
        if not dataframes:
            return None
        primary_name = list(dataframes.keys())[0]
        df = dataframes[primary_name]

        # Find date column
        date_col = None
        for col in df.columns:
            if "date" in col.lower() or "time" in col.lower() or "timestamp" in col.lower():
                try:
                    pd.to_datetime(df[col].dropna().head(10))
                    date_col = col
                    break
                except Exception:
                    continue

        if not date_col:
            return None

        temp_df = df.copy()
        temp_df["_parsed_date"] = pd.to_datetime(temp_df[date_col], errors="coerce")
        temp_df = temp_df.dropna(subset=["_parsed_date"])
        if temp_df.empty:
            return None

        # Choose grouping frequency
        span_days = (temp_df["_parsed_date"].max() - temp_df["_parsed_date"].min()).days
        if span_days > 730:
            temp_df["_period"] = temp_df["_parsed_date"].dt.strftime("%Y")
            period_name = "Year"
        elif span_days > 60:
            temp_df["_period"] = temp_df["_parsed_date"].dt.strftime("%Y-%m")
            period_name = "Month"
        else:
            temp_df["_period"] = temp_df["_parsed_date"].dt.strftime("%Y-%m-%d")
            period_name = "Date"

        num_cols = [c for c in df.select_dtypes(include=[np.number]).columns if not c.lower().endswith("id") and not c.lower().endswith("code")]
        primary_num = num_cols[0] if num_cols else None

        if primary_num:
            grouped = temp_df.groupby("_period").agg(
                volume=("order_id" if "order_id" in temp_df.columns else "_parsed_date", "count"),
                metric_sum=(primary_num, "sum"),
                metric_avg=(primary_num, "mean")
            ).reset_index()
            headers = [period_name, "Observations", f"Total {primary_num.replace('_', ' ').title()}", f"Average {primary_num.replace('_', ' ').title()}"]
        else:
            grouped = temp_df.groupby("_period").size().reset_index(name="volume")
            headers = [period_name, "Observations", "Share of Total"]

        grouped = grouped.sort_values(by="_period", ascending=True).tail(8)

        rows = []
        for _, r in grouped.iterrows():
            if primary_num:
                rows.append([
                    str(r["_period"]),
                    f"{int(r['volume']):,}",
                    ReportService.format_cell_value(r["metric_sum"]),
                    ReportService.format_cell_value(r["metric_avg"])
                ])
            else:
                total_vol = len(temp_df)
                pct = round((r["volume"] / total_vol) * 100, 1) if total_vol > 0 else 0
                rows.append([
                    str(r["_period"]),
                    f"{int(r['volume']):,}",
                    f"{pct}%"
                ])

        return {
            "title": f"Longitudinal Cadence & Temporal Dynamics ({period_name}-over-{period_name})",
            "subtitle": f"Temporal aggregations based on '{date_col}'",
            "headers": headers,
            "rows": rows,
            "alignments": ["left", "right", "right", "right"] if primary_num else ["left", "right", "right"],
            "data": [headers, *rows]
        }

