    @classmethod
    async def synthesize_ai_pdf_briefing(
        cls,
        dataset_name: str,
        domain: str,
        health_score: int,
        kpis: List[Dict[str, Any]],
        insights: List[Dict[str, Any]],
        anomalies: List[Dict[str, Any]],
        dataframes: Optional[Dict[str, pd.DataFrame]] = None
    ) -> Dict[str, Any]:
        """
        Uses the configured AI API key (Gemini / OpenAI / Anthropic / DeepSeek)
        via LLMOrchestrator to synthesize executive briefing insights and directives for the PDF.
        """
        kpi_summary = ", ".join(f"{k.get('display_name')}: {k.get('formatted_value')}" for k in (kpis or [])[:5])
        ins_summary = "; ".join(f"{i.get('title')}: {i.get('description')}" for i in (insights or [])[:3])
        anom_summary = f"{len(anomalies)} outliers detected" if anomalies else "Zero critical anomalies"

        system_prompt = (
            "You are Datova's Principal AI Business Intelligence & Quantitative Strategy Analyst. "
            "Synthesize an elite C-Suite Executive Business Briefing for the provided dataset. "
            "Return structured, concise JSON with bold quantitative metrics and clear actionable directives."
        )

        user_prompt = (
            f"Dataset: '{dataset_name}' in domain '{domain}'. "
            f"Health Score: {health_score}/100. "
            f"Key KPIs: {kpi_summary}. "
            f"Empirical Insights: {ins_summary}. "
            f"Anomaly Profile: {anom_summary}. "
            f"Generate a JSON object with: "
            f"1. 'executive_headline' (string) "
            f"2. 'strategic_takeaway' (string) "
            f"3. 'directives' (array of 3 objects with 'title' and 'action')"
        )

        try:
            raw_json = await LLMOrchestrator.query_llm(system_prompt, user_prompt, response_format_json=True)
            cleaned = LLMOrchestrator._clean_llm_json(raw_json)
            parsed = json.loads(cleaned)
            if isinstance(parsed, dict) and "directives" in parsed:
                return parsed
        except Exception as e:
            logger.warning(f"AI synthesis fallback invoked: {e}")

        # Grounded deterministic fallback
        top_kpi_name = kpis[0].get("display_name", "Primary Indicator") if kpis else "Core Metric"
        top_kpi_val = kpis[0].get("formatted_value", "Optimal") if kpis else "Active"
        return {
            "executive_headline": f"Autonomous Commercial Synthesis • {domain}",
            "strategic_takeaway": f"Evaluation confirms robust operations anchored by {top_kpi_name} ({top_kpi_val}) with high data fidelity.",
            "directives": [
                {"title": "High-Yield Channel Allocation", "action": f"Prioritize operational resourcing around top-performing clusters in {domain}."},
                {"title": "Outlier & Variance Safeguards", "action": "Maintain automated bounds checking to preserve reporting fidelity."},
                {"title": "Strategic Run-Rate Pacing", "action": "Align capacity targets with empirical longitudinal distributions."}
            ]
        }

