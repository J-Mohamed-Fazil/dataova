    @classmethod
    def generate_dynamic_sections(
        cls,
        dataset_name: str,
        domain: str,
        health_info: Dict[str, Any],
        kpis: List[Dict[str, Any]],
        insights: List[Dict[str, Any]],
        anomalies: List[Dict[str, Any]],
        dataframes: Optional[Dict[str, pd.DataFrame]] = None
    ) -> List[Dict[str, Any]]:
        """
        Dynamically designs and formats report sections tailored to the uploaded dataset's
        domain, schema, cardinality, metrics, and relationships.
        Combines narrative synthesis, interactive dashboard charts with meaningful insights,
        and precision-aligned data tables.
        """
        dataframes = dataframes or {}
        sections = []
        order = 0

        total_records = sum(len(df) for df in dataframes.values()) if dataframes else 0
        table_names = list(dataframes.keys())
        primary_name = table_names[0] if table_names else "Primary Table"
        primary_df = dataframes.get(primary_name, pd.DataFrame())

