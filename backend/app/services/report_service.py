        chart_h = height - 48.0

        # Baseline Axis
        d.add(Line(chart_x, chart_y, chart_x + chart_w, chart_y, strokeColor=colors.HexColor('#CBD5E1'), strokeWidth=1))

        n_items = len(display_items)
        slot_w = chart_w / max(n_items, 1)
        bar_w = min(36.0, slot_w * 0.52)

        for idx, item in enumerate(display_items):
            val = float(item.get("value", 0))
            bar_h = max(3.0, (val / max_val) * (chart_h - 14.0))
            bx = chart_x + idx * slot_w + (slot_w - bar_w) / 2.0
            by = chart_y
            bar_color = palette[idx % len(palette)]

            # Vertical Bar
            d.add(Rect(bx, by, bar_w, bar_h, rx=2.0, ry=2.0, fillColor=bar_color, strokeColor=None))

            # Value label on top
            val_str = cls.format_cell_value(val)
            if len(val_str) > 8:
                val_str = f"{val/1000:.1f}k" if val >= 1000 else val_str[:7]
            d.add(String(bx + bar_w / 2.0, by + bar_h + 2.5, val_str, fontName='Helvetica-Bold', fontSize=6, fillColor=colors.HexColor('#0F172A'), textAnchor='middle'))

            # X Label below
            lbl = str(item.get("label", ""))
            if len(lbl) > 10:
                lbl = lbl[:8] + ".."
            d.add(String(bx + bar_w / 2.0, by - 10.0, lbl, fontName='Helvetica', fontSize=6, fillColor=colors.HexColor('#475569'), textAnchor='middle'))

        return d

